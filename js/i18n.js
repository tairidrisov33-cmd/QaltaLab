  var lang = 'ru';
  var cache = Object.create(null);

  function t(s) {
    if (typeof s !== 'string') return s;
    var service = s.length > 1 && s.charAt(0) === '%' && s.charAt(s.length - 1) === '%';
    if (lang === 'ru') return service ? '' : s;
    if (cache[s] !== undefined) return cache[s];
    var v = KK[s];
    if (v === undefined) v = service ? '' : s;   // не переведено — показываем русский, а не пустоту
    cache[s] = v;
    return v;
  }

  // Подстановка чисел в уже переведённое предложение.
  // Нужна для карточек открытия: склеивать куски нельзя — в казахском
  // другой порядок слов, и склейка развалилась бы.
  function fmt(s, vars) {
    var out = t(s);
    Object.keys(vars || {}).forEach(function (k) {
      out = out.split('{' + k + '}').join(String(vars[k]));
    });
    return out;
  }

  var prev = 'ru';
  var back = null;   // казахский текст -> русский ключ, строится по требованию

  // Перевод уже нарисованного экрана без перерисовки: так идущий опыт не
  // теряет замеры. Узлы, созданные через h(), помнят свой ключ; остальной
  // текст ищем по словарю в обратную сторону.
  function keyOf(node) {
    if (node.__ru !== undefined) return node.__ru;
    var v = node.nodeValue, s = v.trim();
    if (!s) return null;
    var k = null;
    if (prev === 'ru') k = KK[s] !== undefined ? s : null;
    else {
      if (!back) { back = Object.create(null); Object.keys(KK).forEach(function (r) { back[KK[r]] = r; }); }
      k = back[s] || null;
    }
    if (k === null) return null;
    return v.replace(s, k);
  }

  function retranslate(root) {
    var walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    var list = [], n;
    while ((n = walk.nextNode())) list.push(n);
    list.forEach(function (node) {
      var k = keyOf(node);
      if (k === null) return;
      var s = k.trim();
      node.nodeValue = k.replace(s, t(s));
    });
  }

  function set(next) {
    if (next !== 'ru' && next !== 'kk') next = 'ru';
    if (next === lang) return;
    prev = lang;
    lang = next;
    cache = Object.create(null);
    try { localStorage.setItem('spl.lang', lang); } catch (e) {}
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
    if (A.app && A.app.render) A.app.render();
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem('spl.lang'); } catch (e) {}
    if (!saved) saved = (navigator.language || 'ru').slice(0, 2) === 'kk' ? 'kk' : 'ru';
    lang = saved === 'kk' ? 'kk' : 'ru';
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
  }

  A.i18n = {
    t: t, fmt: fmt, set: set, init: init, retranslate: retranslate,
    get lang() { return lang; },
    dict: KK
  };
