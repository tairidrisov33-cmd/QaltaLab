  var lang = 'ru';
  var cache = Object.create(null);

  function t(s) {
    if (typeof s !== 'string') return s;
    var service = s.length > 1 && s.charAt(0) === '%' && s.charAt(s.length - 1) === '%';
    if (lang === 'ru') return service ? '' : s;
    if (cache[s] !== undefined) return cache[s];
    var v = KK[s];
    if (v === undefined) v = service ? '' : s;   // не переведено — показываем русский, а не пустоту
    cache[s] = v;
    return v;
  }

  // Подстановка чисел в уже переведённое предложение.
  // Нужна для карточек открытия: склеивать куски нельзя — в казахском
  // другой порядок слов, и склейка развалилась бы.
  function fmt(s, vars) {
    var out = t(s);
    Object.keys(vars || {}).forEach(function (k) {
      out = out.split('{' + k + '}').join(String(vars[k]));
    });
    return out;
  }

  function set(next) {
    if (next !== 'ru' && next !== 'kk') next = 'ru';
    if (next === lang) return;
    lang = next;
    cache = Object.create(null);
    try { localStorage.setItem('spl.lang', lang); } catch (e) {}
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
    if (A.app && A.app.render) A.app.render();
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem('spl.lang'); } catch (e) {}
    if (!saved) saved = (navigator.language || 'ru').slice(0, 2) === 'kk' ? 'kk' : 'ru';
    lang = saved === 'kk' ? 'kk' : 'ru';
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
  }

  A.i18n = {
    t: t, fmt: fmt, set: set, init: init,
    get lang() { return lang; },
    dict: KK
  };
